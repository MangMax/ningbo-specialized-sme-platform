it('shows configuration without source or verification claims and scopes pending feedback to the requested action', async () => {
  await open()
  expect(view.text()).toContain('已配置')
  expect(view.text()).not.toMatch(/有效来源|未验证|页面保存$/)
  const writeText = vi.fn().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  let finish!: (value: unknown) => void
  request.mockReturnValueOnce(new Promise(resolve => { finish = resolve }))
  await view.get('[aria-label="复制 OCR token"]').trigger('click')
  expect(view.get('[aria-label="复制 OCR token"]').attributes('aria-busy')).toBe('true')
  expect(view.get('[data-testid="save-ocr-token"]').attributes('aria-busy')).toBe('false')
  expect(view.get('[aria-label="刷新密钥配置"]').find('[data-slot="loading-indicator"]').exists()).toBe(false)
  expect(view.get('[data-testid="save-ocr-token"]').text()).toBe('保存 OCR token')
  finish({ value: 'synthetic-copy-only' }); await flushPromises()
  expect(writeText).toHaveBeenCalledWith('synthetic-copy-only')
  expect(view.text()).toContain('已复制完整OCR token')
  expect(view.text()).not.toContain('synthetic-copy-only')
  expect(view.get('[aria-label="复制 OCR token"]').attributes('aria-busy')).toBe('false')

  request.mockReturnValueOnce(new Promise(resolve => { finish = resolve }))
  await view.get('[aria-label="刷新密钥配置"]').trigger('click')
  expect(view.get('[aria-label="刷新密钥配置"]').find('[data-slot="loading-indicator"]').exists()).toBe(true)
  expect(view.get('[aria-label="复制 OCR token"]').attributes('aria-busy')).toBe('false')
  finish(status()); await flushPromises()
})
