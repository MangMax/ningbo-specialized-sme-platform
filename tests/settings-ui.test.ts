// @vitest-environment happy-dom
import { mount, flushPromises } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
import CredentialSettings from '../components/settings/CredentialSettings.vue'
const request = vi.fn()
let view: ReturnType<typeof mount>
afterEach(() => { view?.unmount(); vi.unstubAllGlobals(); vi.restoreAllMocks() })
function status(source = 'saved') { return { ocrToken: { configured: true, source, masked: 'syn********ret', updatedAt: null, hasSaved: source === 'saved' } } }
function tab(name: string) {
  const match = view.findAll('[role="tab"]').find(item => item.text() === name)
  if (!match) throw new Error(`Missing platform tab: ${name}`)
  return match
}
async function open() {
  vi.stubGlobal('$fetch', request)
  request.mockReset().mockResolvedValue(status())
  view = mount(CredentialSettings, { attachTo: document.body })
  expect(request).not.toHaveBeenCalled()
  await view.get('#settings-admin-token').setValue('synthetic-admin')
  await view.get('form').trigger('submit')
  await flushPromises()
}
it('loads only masked state after authorization, explicitly reveals/hides and copies the full value from a masked state', async () => {
  await open()
  expect(view.text()).toContain('syn********ret')
  expect(view.text().includes('synthetic-secret')).toBe(false)
  request.mockResolvedValueOnce({ value: 'synthetic-secret' })
  await view.get('[aria-label="显示 OCR token"]').trigger('click'); await flushPromises()
  expect(view.text().includes('synthetic-secret')).toBe(true)
  await view.get('[aria-label="隐藏 OCR token"]').trigger('click')
  expect(view.text().includes('synthetic-secret')).toBe(false)
  const writeText = vi.fn().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  request.mockResolvedValueOnce({ value: 'synthetic-secret' })
  await view.get('[aria-label="复制 OCR token"]').trigger('click'); await flushPromises()
  expect(writeText.mock.calls[0]?.[0] === 'synthetic-secret').toBe(true)
  expect(view.text()).toContain('已复制')
  expect(view.text().includes('synthetic-secret')).toBe(false)
})
it('preserves replacement input after failure and retries save; clears only the saved override', async () => {
  await open()
  await view.get('#ocr-token-replacement').setValue('synthetic-new')
  request.mockRejectedValueOnce(new Error('synthetic sensitive error'))
  await view.findAll('form')[1]!.trigger('submit'); await flushPromises()
  expect(view.get<HTMLInputElement>('#ocr-token-replacement').element.value === 'synthetic-new').toBe(true)
  expect(view.text()).toContain('重试')
  expect(view.text()).not.toContain('synthetic sensitive error')
  request.mockResolvedValueOnce(status())
  await view.findAll('form')[1]!.trigger('submit'); await flushPromises()
  expect(view.get<HTMLInputElement>('#ocr-token-replacement').element.value).toBe('')
  expect(view.text()).toContain('已保存')
  request.mockResolvedValueOnce(status('NUXT_OCR_TOKEN'))
  await view.get('[data-testid="clear-ocr-token"]').trigger('click'); await flushPromises()
  expect(view.text()).toContain('NUXT_OCR_TOKEN')
  expect(request.mock.calls.at(-1)?.[1]).toMatchObject({ method: 'DELETE', body: { key: 'ocrToken' } })
})
it('reports clipboard failure and clears page memory on authorization change and unmount', async () => {
  await open()
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: vi.fn().mockRejectedValue(new Error('denied')) } })
  request.mockResolvedValueOnce({ value: 'synthetic-secret' })
  await view.get('[aria-label="复制 OCR token"]').trigger('click'); await flushPromises()
  expect(view.text()).toContain('复制失败')
  expect(view.text()).not.toContain('已复制')
  request.mockResolvedValueOnce({ value: 'synthetic-secret' })
  await view.get('[aria-label="显示 OCR token"]').trigger('click'); await flushPromises()
  await view.get('#settings-admin-token').setValue('another-admin')
  expect(view.text().includes('synthetic-secret')).toBe(false)
  expect(view.find('[aria-label="显示 OCR token"]').exists()).toBe(false)
})
it('disables actions for an unconfigured value and rejects late reveal responses after leaving the page', async () => {
  await open()
  request.mockResolvedValueOnce({ ocrToken: { configured: false, source: 'none', masked: '', updatedAt: null, hasSaved: false } })
  await view.get('form').trigger('submit'); await flushPromises()
  expect(view.text()).toContain('未配置')
  expect(view.get('[aria-label="显示 OCR token"]').attributes('disabled')).toBeDefined()
  expect(view.get('[aria-label="复制 OCR token"]').attributes('disabled')).toBeDefined()
  request.mockResolvedValueOnce(status())
  await view.get('form').trigger('submit'); await flushPromises()
  let finish!: (value: unknown) => void
  request.mockReturnValueOnce(new Promise(resolve => { finish = resolve }))
  await view.get('[aria-label="显示 OCR token"]').trigger('click')
  expect(view.attributes('aria-busy')).toBe('true')
  expect(view.get('[aria-label="显示 OCR token"]').attributes('disabled')).toBeDefined()
  view.unmount()
  finish({ value: 'synthetic-late-secret' }); await flushPromises()
  view = mount(CredentialSettings, { attachTo: document.body })
  expect(view.get<HTMLInputElement>('#settings-admin-token').element.value).toBe('')
  expect(view.text().includes('synthetic-late-secret')).toBe(false)
  expect(view.find('section').exists()).toBe(false)
})
it('retains focus through saving and returns to the replacement field after a successful save', async () => {
  await open()
  await view.get('#ocr-token-replacement').setValue('synthetic-focused-save')
  let finish!: (value: unknown) => void
  request.mockReturnValueOnce(new Promise(resolve => { finish = resolve }))
  view.get<HTMLButtonElement>('[data-testid="save-ocr-token"]').element.focus()
  await view.findAll('form')[1]!.trigger('submit')
  expect(view.attributes('aria-busy')).toBe('true')
  expect(view.get<HTMLButtonElement>('[data-testid="save-ocr-token"]').element.disabled).toBe(true)
  expect(view.findAll<HTMLButtonElement>('[role="tab"]').every(item => item.element.disabled)).toBe(true)
  finish(status()); await flushPromises()
  expect(view.attributes('aria-busy')).toBe('false')
  expect(document.activeElement?.id).toBe('ocr-token-replacement')
})
it('clears authorization and revealed values on pagehide before browser history can retain them', async () => {
  await open()
  request.mockResolvedValueOnce({ value: 'synthetic-secret' })
  await view.get('[aria-label="显示 OCR token"]').trigger('click'); await flushPromises()
  expect(view.text().includes('synthetic-secret')).toBe(true)
  window.dispatchEvent(new Event('pagehide'))
  await flushPromises()
  expect(view.get<HTMLInputElement>('#settings-admin-token').element.value).toBe('')
  expect(view.text().includes('synthetic-secret')).toBe(false)
  expect(view.find('section').exists()).toBe(false)
})

it('manages Cookie independently with masked copy, reveal, hide, failed save retry and environment fallback', async () => {
  await open()
  const both = (source = 'saved') => ({ ...status(), miitCookie: { configured: true, source, masked: 'ses********ret', hasSaved: source === 'saved', updatedAt: null } })
  request.mockResolvedValueOnce(both())
  await view.get('form').trigger('submit'); await flushPromises()
  await tab('工信部平台').trigger('keydown', { key: 'Enter' }); await flushPromises()
  expect(view.text()).toContain('ses********ret')
  request.mockResolvedValueOnce({ value: 'session=synthetic-cookie-secret' })
  await view.get('[aria-label="显示平台 Cookie"]').trigger('click'); await flushPromises()
  expect(view.text().includes('session=synthetic-cookie-secret')).toBe(true)
  await view.get('[aria-label="隐藏平台 Cookie"]').trigger('click')
  expect(view.text().includes('session=synthetic-cookie-secret')).toBe(false)
  const writeText = vi.fn().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  request.mockResolvedValueOnce({ value: 'session=synthetic-cookie-secret' })
  await view.get('[aria-label="复制平台 Cookie"]').trigger('click'); await flushPromises()
  expect(writeText.mock.calls[0]?.[0] === 'session=synthetic-cookie-secret').toBe(true)
  expect(view.text()).toContain('已复制完整平台 Cookie')
  expect(view.text().includes('session=synthetic-cookie-secret')).toBe(false)
  await view.get('#miit-cookie-replacement').setValue('session=synthetic-new-cookie')
  request.mockRejectedValueOnce(new Error('sensitive echo'))
  await view.findAll('form')[1]!.trigger('submit'); await flushPromises()
  expect(view.get<HTMLInputElement>('#miit-cookie-replacement').element.value === 'session=synthetic-new-cookie').toBe(true)
  request.mockResolvedValueOnce(both())
  await view.findAll('form')[1]!.trigger('submit'); await flushPromises()
  expect(request.mock.calls.at(-1)?.[1]).toMatchObject({ method: 'PATCH', body: { miitCookie: 'session=synthetic-new-cookie' } })
  expect(view.find('#ocr-token-replacement').exists()).toBe(false)
  request.mockResolvedValueOnce(both('MIIT_COOKIE_FILE'))
  await view.get('[data-testid="clear-miit-cookie"]').trigger('click'); await flushPromises()
  expect(view.text()).toContain('MIIT_COOKIE_FILE')
  expect(request.mock.calls.at(-1)?.[1]).toMatchObject({ method: 'DELETE', body: { key: 'miitCookie' } })
})
it('disables an absent Cookie and clears revealed Cookie and authorization when leaving the page', async () => {
  await open()
  request.mockResolvedValueOnce({ ...status(), miitCookie: { configured: false, source: 'none', masked: '', updatedAt: null, hasSaved: false } })
  await view.get('form').trigger('submit'); await flushPromises()
  await tab('工信部平台').trigger('keydown', { key: 'Enter' }); await flushPromises()
  expect(view.get('[aria-label="显示平台 Cookie"]').attributes('disabled')).toBeDefined()
  expect(view.get('[aria-label="复制平台 Cookie"]').attributes('disabled')).toBeDefined()
  request.mockResolvedValueOnce({ ...status(), miitCookie: { configured: true, source: 'MIIT_COOKIE', masked: 'ses********ret', updatedAt: null, hasSaved: false } })
  await view.get('form').trigger('submit'); await flushPromises()
  request.mockResolvedValueOnce({ value: 'session=synthetic-leaving' })
  await view.get('[aria-label="显示平台 Cookie"]').trigger('click'); await flushPromises()
  expect(view.text().includes('session=synthetic-leaving')).toBe(true)
  window.dispatchEvent(new Event('pagehide')); await flushPromises()
  expect(view.get<HTMLInputElement>('#settings-admin-token').element.value).toBe('')
  expect(view.text().includes('session=synthetic-leaving')).toBe(false)
  expect(view.find('section').exists()).toBe(false)
})

it('shows one platform tab at a time, retains separate drafts and hides revealed values when switching', async () => {
  await open()
  request.mockResolvedValueOnce({ ...status(), miitCookie: { configured: true, source: 'MIIT_COOKIE', masked: 'ses********ret', updatedAt: null, hasSaved: false } })
  await view.get('form').trigger('submit'); await flushPromises()
  expect(tab('OCR').text()).toBe('OCR')
  expect(view.find('#miit-cookie-replacement').exists()).toBe(false)
  await view.get('#ocr-token-replacement').setValue('synthetic-ocr-draft')
  request.mockResolvedValueOnce({ value: 'synthetic-revealed-token' })
  await view.get('[aria-label="显示 OCR token"]').trigger('click'); await flushPromises()
  expect(view.text().includes('synthetic-revealed-token')).toBe(true)
  await tab('工信部平台').trigger('keydown', { key: 'Enter' }); await flushPromises()
  expect(tab('工信部平台').attributes('aria-selected')).toBe('true')
  expect(view.find('#ocr-token-replacement').exists()).toBe(false)
  await view.get('#miit-cookie-replacement').setValue('session=synthetic-cookie-draft')
  await tab('OCR').trigger('keydown', { key: 'Enter' }); await flushPromises()
  expect(view.get<HTMLInputElement>('#ocr-token-replacement').element.value === 'synthetic-ocr-draft').toBe(true)
  expect(view.text().includes('synthetic-revealed-token')).toBe(false)
  expect(view.find('[aria-label="显示 OCR token"]').exists()).toBe(true)
  await tab('工信部平台').trigger('keydown', { key: 'Enter' }); await flushPromises()
  expect(view.get<HTMLInputElement>('#miit-cookie-replacement').element.value === 'session=synthetic-cookie-draft').toBe(true)
 })
