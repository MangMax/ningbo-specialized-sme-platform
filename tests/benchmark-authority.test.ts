it('keeps matching literal manifests unvalidated even with plausible provenance', () => {
  const { artifact, workload } = currentExpected()
  expect(compareCurrentReadAuthority(artifact, workload, currentObservation())).toEqual({
    status: 'COMPARED_UNVALIDATED', qualified: false, runtimeQualified: false,
    reason: 'Independent delivery receipts and actual runtime/request verification remain required',
  })
})

