-- Run against the isolated target after staging and verifying events.db.
\set ON_ERROR_STOP on
BEGIN ISOLATION LEVEL REPEATABLE READ;
CREATE SCHEMA runtime_logs;
SET LOCAL search_path TO runtime_logs, pg_catalog;

CREATE TABLE log_policy (
  id bigint PRIMARY KEY CHECK (id = 1),
  "retentionDays" bigint NOT NULL CHECK ("retentionDays" BETWEEN 1 AND 365),
  "maxBytes" bigint NOT NULL CHECK ("maxBytes" BETWEEN 1048576 AND 4294967296),
  pruned bigint NOT NULL DEFAULT 0 CHECK (pruned >= 0),
  cleared bigint NOT NULL DEFAULT 0 CHECK (cleared >= 0),
  logical_bytes bigint NOT NULL DEFAULT 0 CHECK (logical_bytes >= 0)
);

CREATE TABLE log_collection (
  id bigint PRIMARY KEY CHECK (id = 1),
  collection text NOT NULL,
  revision bigint NOT NULL CHECK (revision BETWEEN 0 AND 9007199254740991)
);

CREATE TABLE log_events (
  seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id text COLLATE "C" NOT NULL UNIQUE,
  timestamp text COLLATE "C" NOT NULL,
  level text COLLATE "C" NOT NULL,
  source text COLLATE "C" NOT NULL,
  module text COLLATE "C",
  operation text COLLATE "C" NOT NULL,
  outcome text COLLATE "C" NOT NULL,
  "requestId" text COLLATE "C",
  "traceId" text COLLATE "C",
  "taskId" text COLLATE "C",
  "fileId" bigint,
  "batchId" text COLLATE "C",
  "resourceId" text COLLATE "C",
  summary text NOT NULL,
  detail text NOT NULL
);

INSERT INTO log_policy (id, "retentionDays", "maxBytes", pruned, cleared)
SELECT id, "retentionDays", "maxBytes", pruned, cleared FROM :"staging".log_policy;
INSERT INTO log_collection (id, collection, revision)
SELECT id, collection, revision FROM :"staging".log_collection;

-- Historical stores without the module column have no recorded module.
SELECT CASE WHEN EXISTS (
  SELECT 1 FROM pg_attribute
  WHERE attrelid = to_regclass(format('%I.log_events', :'staging'))
    AND attname = 'module' AND NOT attisdropped
) THEN 'module' ELSE 'NULL::text' END AS module_projection
\gset
INSERT INTO log_events (
  seq, id, timestamp, level, source, module, operation, outcome, "requestId", "traceId",
  "taskId", "fileId", "batchId", "resourceId", summary, detail
)
SELECT seq, id, timestamp, level, source, :module_projection, operation, outcome, "requestId", "traceId",
  "taskId", "fileId", "batchId", "resourceId", summary, detail
FROM :"staging".log_events;

-- The runtime capacity accounts for the two persisted JSON representations.
UPDATE log_policy SET logical_bytes = (
  SELECT coalesce(sum(octet_length(summary)::bigint + octet_length(detail)), 0)
  FROM log_events
);

-- Deleted events can leave a high-water mark above the maximum retained seq.
WITH sequence_highs AS (
  SELECT CASE WHEN to_jsonb(s)->>'seq_sqlite_storage' = 'integer'
      THEN ('x' || substr(seq::text, 3))::bit(64)::bigint
      ELSE seq::text::bigint END AS seq
  FROM :"staging".sqlite_sequence s WHERE name = 'log_events'
  UNION ALL
  SELECT max(seq) FROM log_events
), sequence_high AS (
  SELECT max(seq) AS seq FROM sequence_highs
)
SELECT setval(pg_get_serial_sequence('runtime_logs.log_events', 'seq'),
              greatest(seq, 1), coalesce(seq >= 1, false))
FROM sequence_high;

CREATE INDEX log_timestamp ON log_events (timestamp, seq);
CREATE INDEX log_level ON log_events (level, seq);
CREATE INDEX log_source ON log_events (source, seq);
CREATE INDEX log_module ON log_events (module, seq);
CREATE INDEX log_operation ON log_events (operation, seq);
CREATE INDEX log_outcome ON log_events (outcome, seq);
CREATE INDEX "log_requestId" ON log_events ("requestId", seq);
CREATE INDEX "log_traceId" ON log_events ("traceId", seq);
CREATE INDEX "log_taskId" ON log_events ("taskId", seq);
CREATE INDEX "log_fileId" ON log_events ("fileId", seq);
CREATE INDEX "log_batchId" ON log_events ("batchId", seq);
CREATE INDEX "log_resourceId" ON log_events ("resourceId", seq);
ANALYZE log_policy, log_collection, log_events;
COMMIT;
