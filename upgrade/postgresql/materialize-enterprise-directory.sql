\set ON_ERROR_STOP on
BEGIN;
CREATE SCHEMA business;
SET LOCAL search_path TO business, public;

CREATE TABLE enterprise (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uscc_norm text UNIQUE,
  name text NOT NULL,
  name_norm text NOT NULL,
  district text,
  city text,
  reg_status text,
  quality_flags text DEFAULT '[]'
);

CREATE TABLE enterprise_merge (
  from_enterprise_id bigint PRIMARY KEY REFERENCES enterprise(id) ON DELETE RESTRICT,
  into_enterprise_id bigint NOT NULL REFERENCES enterprise(id) ON DELETE RESTRICT,
  basis text NOT NULL,
  recorded_at text NOT NULL,
  CHECK (from_enterprise_id <> into_enterprise_id),
  CHECK (from_enterprise_id BETWEEN 1 AND 9007199254740991),
  CHECK (into_enterprise_id BETWEEN 1 AND 9007199254740991)
);

CREATE TABLE enterprise_region (
  code text PRIMARY KEY,
  name text NOT NULL,
  parent_code text REFERENCES enterprise_region(code),
  level bigint NOT NULL CHECK (level BETWEEN 1 AND 3)
);

CREATE TABLE enterprise_industry (
  code text PRIMARY KEY,
  input_id text NOT NULL UNIQUE,
  name text NOT NULL,
  parent_code text REFERENCES enterprise_industry(code),
  level bigint NOT NULL CHECK (level BETWEEN 0 AND 3),
  description text
);

CREATE TABLE enterprise_directory (
  enterprise_id bigint PRIMARY KEY REFERENCES enterprise(id),
  district_code text REFERENCES enterprise_region(code),
  township_code text REFERENCES enterprise_region(code),
  industry_code text REFERENCES enterprise_industry(code),
  removed_reason text,
  revision bigint NOT NULL DEFAULT 1
);

CREATE TABLE enterprise_address (
  enterprise_id bigint NOT NULL REFERENCES enterprise(id),
  kind text NOT NULL CHECK (kind IN ('registered', 'operating')),
  address text NOT NULL CHECK (length(trim(address)) BETWEEN 1 AND 500),
  PRIMARY KEY (enterprise_id, kind)
);

CREATE TABLE stored_file (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rel_path text NOT NULL UNIQUE,
  display_name text,
  filename text NOT NULL,
  ext text NOT NULL,
  bytes bigint NOT NULL,
  sha256 text NOT NULL,
  created_at text NOT NULL,
  removed_at text
);

CREATE TABLE enterprise_source_channel (code text PRIMARY KEY, name text NOT NULL);
CREATE TABLE enterprise_source_list_type (code text PRIMARY KEY, name text NOT NULL);

CREATE TABLE enterprise_source (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module text NOT NULL,
  business_table text NOT NULL,
  version_key text NOT NULL,
  channel_code text NOT NULL REFERENCES enterprise_source_channel(code),
  list_type_code text NOT NULL REFERENCES enterprise_source_list_type(code),
  acquired_on text,
  series text NOT NULL,
  file_id bigint REFERENCES stored_file(id),
  sha256 text,
  UNIQUE (module, business_table, version_key)
);

CREATE TABLE enterprise_source_link (
  enterprise_id bigint NOT NULL REFERENCES enterprise(id),
  source_id bigint NOT NULL REFERENCES enterprise_source(id),
  PRIMARY KEY (enterprise_id, source_id)
);

INSERT INTO enterprise SELECT id, uscc_norm, name, name_norm, district, city, reg_status, quality_flags FROM :"staging".enterprise;
INSERT INTO enterprise_merge SELECT from_enterprise_id, into_enterprise_id, basis, recorded_at FROM :"staging".enterprise_merge;
INSERT INTO enterprise_region SELECT code, name, parent_code, level FROM :"staging".enterprise_region;
INSERT INTO enterprise_industry SELECT code, input_id, name, parent_code, level, description FROM :"staging".enterprise_industry;
INSERT INTO enterprise_directory SELECT enterprise_id, district_code, township_code, industry_code, removed_reason, revision FROM :"staging".enterprise_directory;
INSERT INTO enterprise_address SELECT enterprise_id, kind, address FROM :"staging".enterprise_address;
INSERT INTO stored_file SELECT id, rel_path, display_name, filename, ext, bytes, sha256, created_at, removed_at FROM :"staging".stored_file;
INSERT INTO enterprise_source_channel SELECT code, name FROM :"staging".enterprise_source_channel;
INSERT INTO enterprise_source_list_type SELECT code, name FROM :"staging".enterprise_source_list_type;
INSERT INTO enterprise_source SELECT id, module, business_table, version_key, channel_code, list_type_code, acquired_on, series, file_id, sha256 FROM :"staging".enterprise_source;
INSERT INTO enterprise_source_link SELECT enterprise_id, source_id FROM :"staging".enterprise_source_link;

SELECT format('SELECT setval(%L, %s, %L)',
              pg_get_serial_sequence(format('business.%I', name), 'id'),
              greatest(seq, 1), coalesce(seq >= 1, false))
FROM (
  SELECT name, max(high_water) AS seq
  FROM (
    -- Staging uses tagged bytea when any SQLite sequence cell has mixed storage.
    SELECT name, CASE WHEN to_jsonb(s)->>'seq_sqlite_storage' = 'integer'
        THEN ('x' || substr(seq::text, 3))::bit(64)::bigint
        ELSE seq::text::bigint END AS high_water
    FROM :"staging".sqlite_sequence s
    WHERE name IN ('enterprise', 'enterprise_source', 'stored_file')
    UNION ALL SELECT 'enterprise', max(id) FROM enterprise
    UNION ALL SELECT 'enterprise_source', max(id) FROM enterprise_source
    UNION ALL SELECT 'stored_file', max(id) FROM stored_file
  ) highs GROUP BY name
) sequences
\gexec

CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
CREATE INDEX enterprise_name_norm_idx ON enterprise(name_norm);
CREATE INDEX enterprise_name_trgm_idx ON enterprise USING gin (name_norm COLLATE "C" gin_trgm_ops);
CREATE INDEX enterprise_merge_into_idx ON enterprise_merge(into_enterprise_id);
CREATE INDEX enterprise_directory_region_idx ON enterprise_directory(district_code, township_code, enterprise_id);
CREATE INDEX enterprise_directory_industry_idx ON enterprise_directory(industry_code, enterprise_id);
CREATE INDEX enterprise_source_link_source_idx ON enterprise_source_link(source_id, enterprise_id);
ANALYZE enterprise, enterprise_merge, enterprise_region, enterprise_industry, enterprise_directory,
  enterprise_address, stored_file, enterprise_source, enterprise_source_link;
COMMIT;
