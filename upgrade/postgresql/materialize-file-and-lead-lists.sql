CREATE TABLE lead_list_version (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  series text NOT NULL,
  channel_code text NOT NULL REFERENCES enterprise_source_channel(code),
  list_type_code text NOT NULL REFERENCES enterprise_source_list_type(code),
  acquired_on text NOT NULL,
  file_id bigint NOT NULL REFERENCES stored_file(id),
  file_sha256 text NOT NULL,
  request_hash text NOT NULL,
  created_at text NOT NULL,
  UNIQUE (series, channel_code, list_type_code, acquired_on, file_id)
);
CREATE INDEX lead_list_version_file_idx ON lead_list_version(file_id);

CREATE TABLE lead_list_row (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id bigint NOT NULL REFERENCES lead_list_version(id),
  row_number bigint NOT NULL,
  name text NOT NULL,
  uscc text,
  district text,
  note text,
  enterprise_id bigint REFERENCES enterprise(id),
  review_hash text,
  review_actor text,
  review_basis text,
  reviewed_at text,
  CHECK ((enterprise_id IS NULL) = (review_hash IS NULL)),
  UNIQUE (version_id, row_number)
);

