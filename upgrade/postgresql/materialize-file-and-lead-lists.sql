CREATE TABLE stored_file_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stored_file_id bigint NOT NULL REFERENCES stored_file(id),
  old_display_name text NOT NULL,
  new_display_name text NOT NULL,
  created_at text NOT NULL
);
CREATE INDEX stored_file_audit_file_idx ON stored_file_audit(stored_file_id);

CREATE TABLE file_maintenance_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id bigint NOT NULL REFERENCES stored_file(id),
  revision bigint NOT NULL,
  action text NOT NULL CHECK (action IN ('update', 'remove', 'restore')),
  idempotency_key text,
  request_hash text NOT NULL,
  mode text NOT NULL CHECK (mode IN ('legacy', 'versioned')),
  actor text,
  basis text,
  before_json text NOT NULL,
  after_json text NOT NULL,
  created_at text NOT NULL,
  CONSTRAINT file_maintenance_key_uq UNIQUE (idempotency_key),
  CONSTRAINT file_maintenance_revision_uq UNIQUE (file_id, revision)
);

CREATE TABLE file_physical_intent (
  id text PRIMARY KEY,
  file_id bigint NOT NULL REFERENCES stored_file(id),
  rel_path text NOT NULL,
  sha256 text NOT NULL,
  bytes bigint NOT NULL,
  state text NOT NULL CHECK (state IN ('pending', 'quarantined', 'recovering', 'recovered')),
  delete_key text NOT NULL,
  delete_hash text NOT NULL,
  delete_receipt text,
  recover_key text,
  recover_hash text,
  recover_receipt text,
  created_at text NOT NULL,
  CONSTRAINT file_physical_delete_key_uq UNIQUE (delete_key),
  CONSTRAINT file_physical_recover_key_uq UNIQUE (recover_key)
);
CREATE UNIQUE INDEX file_physical_active_uq ON file_physical_intent(file_id) WHERE state <> 'recovered';
CREATE INDEX file_physical_history_idx ON file_physical_intent(file_id, created_at, id);

INSERT INTO stored_file_audit (id, stored_file_id, old_display_name, new_display_name, created_at)
SELECT id, stored_file_id, old_display_name, new_display_name, created_at FROM :"staging".stored_file_audit;
INSERT INTO file_maintenance_audit
  (id, file_id, revision, action, idempotency_key, request_hash, mode, actor, basis, before_json, after_json, created_at)
SELECT id, file_id, revision, action, idempotency_key, request_hash, mode, actor, basis, before_json, after_json, created_at
FROM :"staging".file_maintenance_audit;
INSERT INTO file_physical_intent
  (id, file_id, rel_path, sha256, bytes, state, delete_key, delete_hash, delete_receipt, recover_key, recover_hash, recover_receipt, created_at)
SELECT id, file_id, rel_path, sha256, bytes, state, delete_key, delete_hash, delete_receipt, recover_key, recover_hash, recover_receipt, created_at
FROM :"staging".file_physical_intent;

CREATE FUNCTION reject_file_audit_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER stored_file_audit_append_only
BEFORE UPDATE OR DELETE ON stored_file_audit
FOR EACH ROW EXECUTE FUNCTION reject_file_audit_mutation();
CREATE TRIGGER file_maintenance_audit_append_only
BEFORE UPDATE OR DELETE ON file_maintenance_audit
FOR EACH ROW EXECUTE FUNCTION reject_file_audit_mutation();

INSERT INTO enterprise_source_channel (code, name) VALUES ('research', '调研走访') ON CONFLICT DO NOTHING;
