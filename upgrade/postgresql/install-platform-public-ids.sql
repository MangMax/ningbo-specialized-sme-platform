\set ON_ERROR_STOP on
BEGIN;
SET LOCAL search_path TO business, pg_catalog;
SELECT to_regclass('business.platform_legacy_query_alias') IS NOT NULL AS platform_separate_public_ids
\gset
\if :platform_separate_public_ids
LOCK TABLE platform_collection, platform_business_observation,
  platform_legacy_query_alias, platform_legacy_relation_alias, platform_legacy_alias_sequence
  IN ACCESS EXCLUSIVE MODE;

ALTER TABLE platform_collection ADD COLUMN public_id bigint;
ALTER TABLE platform_business_observation ADD COLUMN public_id bigint;
UPDATE platform_collection c SET public_id = a.old_id
  FROM platform_legacy_query_alias a WHERE a.collection_id = c.id;
UPDATE platform_business_observation o SET public_id = a.old_id
  FROM platform_legacy_relation_alias a WHERE a.observation_id = o.id;

ALTER TABLE platform_collection ALTER COLUMN public_id SET NOT NULL,
  ALTER COLUMN public_id ADD GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991),
  ADD UNIQUE (public_id), ADD CHECK (public_id BETWEEN 1 AND 9007199254740991);
ALTER TABLE platform_business_observation ALTER COLUMN public_id SET NOT NULL,
  ALTER COLUMN public_id ADD GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991),
  ADD UNIQUE (public_id), ADD CHECK (public_id BETWEEN 1 AND 9007199254740991);

-- Fail if the old sequence row is missing. A filled sequence is marked called,
-- so the next value is above both its retired high water and the imported IDs.
SELECT greatest((SELECT max(public_id) FROM platform_collection), high_water) AS last_query_public_id
  FROM platform_legacy_alias_sequence WHERE namespace='query'
\gset
SELECT greatest((SELECT max(public_id) FROM platform_business_observation), high_water) AS last_relation_public_id
  FROM platform_legacy_alias_sequence WHERE namespace='relation'
\gset
SELECT setval(pg_get_serial_sequence('platform_collection','public_id'),
  greatest(:last_query_public_id,1), :last_query_public_id > 0);
SELECT setval(pg_get_serial_sequence('platform_business_observation','public_id'),
  greatest(:last_relation_public_id,1), :last_relation_public_id > 0);

\ir ../../db/postgresql/platform-public-id-triggers.sql
DROP TABLE platform_legacy_query_alias, platform_legacy_relation_alias, platform_legacy_alias_sequence;
\endif
COMMIT;
