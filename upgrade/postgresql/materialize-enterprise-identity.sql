CREATE TABLE enterprise_kernel_completion (
  id bigint PRIMARY KEY CHECK (id = 1),
  version bigint NOT NULL,
  region_sha256 text,
  industry_sha256 text,
  CHECK ((region_sha256 IS NULL) = (industry_sha256 IS NULL))
);

CREATE TABLE enterprise_alias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id bigint NOT NULL REFERENCES enterprise(id) ON DELETE CASCADE,
  name text NOT NULL,
  name_norm text NOT NULL,
  source_kind text NOT NULL,
  source_ref_id bigint NOT NULL DEFAULT 0,
  valid_from text,
  valid_to text,
  verification_status text NOT NULL DEFAULT 'pending',
  note text,
  created_at text NOT NULL,
  version bigint NOT NULL DEFAULT 1,
  original_name text,
  original_source_kind text,
  original_source_ref_id bigint,
  UNIQUE (enterprise_id, name_norm, source_kind, source_ref_id)
);

CREATE TABLE enterprise_former_name (
  alias_id bigint PRIMARY KEY REFERENCES enterprise_alias(id) ON DELETE CASCADE,
  uscc text,
  renamed_year bigint
);

CREATE TABLE enterprise_alias_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alias_id bigint NOT NULL REFERENCES enterprise_alias(id),
  enterprise_id bigint NOT NULL,
  action text NOT NULL,
  actor text NOT NULL,
  basis text NOT NULL,
  idempotency_key text NOT NULL,
  request_hash text NOT NULL,
  before text NOT NULL,
  after text NOT NULL,
  created_at text NOT NULL,
  UNIQUE (alias_id, idempotency_key)
);

CREATE TABLE enterprise_profile_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id bigint NOT NULL,
  idempotency_key text NOT NULL UNIQUE,
  request_hash text NOT NULL,
  before_version text NOT NULL,
  after_version text NOT NULL,
  before text NOT NULL,
  after text NOT NULL,
  actor text NOT NULL,
  basis text NOT NULL,
  retained_alias_id bigint,
  alias_created bigint NOT NULL DEFAULT 0,
  created_at text NOT NULL
);

INSERT INTO enterprise_kernel_completion (id, version, region_sha256, industry_sha256)
SELECT id, version, region_sha256, industry_sha256 FROM :"staging".enterprise_kernel_completion;
INSERT INTO enterprise_alias (
