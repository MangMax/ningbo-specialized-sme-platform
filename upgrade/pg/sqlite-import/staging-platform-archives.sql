CREATE TABLE platform_archive_value (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_class text NOT NULL,
  bytes bytea,
  byte_length bigint,
  sha256 text,
  created_at text,
  CONSTRAINT platform_archive_value_ck CHECK ((storage_class = 'null' AND bytes IS NULL AND byte_length IS
    NULL AND sha256 IS NULL) OR (storage_class IN ('text','blob') AND bytes IS NOT NULL AND byte_length IS
    NOT NULL AND byte_length = length(bytes) AND sha256 IS NOT NULL AND length(sha256) = 64 AND sha256 !~
    '[^0-9a-f]')),
  CHECK (sha256 IS NULL OR sha256 = encode(pg_catalog.sha256(bytes), 'hex'))
);

CREATE TABLE platform_collection_archive_ref (
  owner_id bigint NOT NULL,
  field text NOT NULL,
  archive_id bigint NOT NULL,
  sealed bigint DEFAULT 0 NOT NULL,
  PRIMARY KEY(owner_id, field),
  CONSTRAINT platform_collection_archive_ref_ck CHECK (field IN ('rawResponse','collectionEvidence','legacyProvenance','request')
    AND sealed IN (0,1))
);

CREATE TABLE platform_collection_legacy_provenance (
  collection_id bigint PRIMARY KEY NOT NULL
    CHECK(collection_id IS NOT NULL AND collection_id BETWEEN 1 AND 9007199254740991),
  origin text NOT NULL CHECK(origin IS NOT NULL AND origin IN ('t04_envelope','supplement')),
  source_identity text NOT NULL,
  source_sha256 text NOT NULL CHECK(source_sha256 IS NOT NULL AND length(source_sha256)=64 AND octet_length(source_sha256)=64 AND source_sha256 !~ '[^0-9a-f]'),
  segment_index bigint NOT NULL CHECK(segment_index IS NOT NULL AND segment_index BETWEEN 0 AND 9007199254740991),
  input_fingerprint text NOT NULL CHECK(input_fingerprint IS NOT NULL AND length(input_fingerprint)=64 AND octet_length(input_fingerprint)=64 AND input_fingerprint !~ '[^0-9a-f]'),
  import_batch_id bigint NOT NULL
    CHECK(import_batch_id IS NOT NULL AND import_batch_id BETWEEN 1 AND 9007199254740991),
  created_at text NOT NULL,
  archive_id bigint NOT NULL UNIQUE
    CHECK(archive_id IS NOT NULL AND archive_id BETWEEN 1 AND 9007199254740991),
  UNIQUE(source_sha256,segment_index)
);

CREATE TABLE platform_observation_archive_ref (
  owner_id bigint NOT NULL,
  field text NOT NULL,
  archive_id bigint NOT NULL,
  sealed bigint DEFAULT 0 NOT NULL,
  PRIMARY KEY(owner_id, field),
  CONSTRAINT platform_observation_archive_ref_ck CHECK (field IN ('rawFields','sourceText','legacyRowSnapshot')
    AND sealed IN (0,1))
);
