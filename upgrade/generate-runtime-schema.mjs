/** Regenerate from an accepted retired schema, or explicitly add disposition DDL to the native baseline. No business rows are exported. */
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
const require = createRequire(import.meta.url)
const Database = require('better-sqlite3')
const { createJiti } = createRequire(import.meta.resolve('nuxt/package.json'))('jiti')
const { assertFinalPlatformRuntime } = await createJiti(import.meta.url, { fsCache: false }).import('../db/schema-phase.ts')
const [source] = process.argv.slice(2)
// Explicit additive owner workflow: regenerate only schema from the checked-in native baseline.
const additive = source === '--add-title-cycle-disposition'
if (!source) throw new Error('Usage: node upgrade/generate-runtime-schema.mjs RETIRED_SCHEMA | --add-title-cycle-disposition')
const db = additive ? new Database(':memory:') : new Database(source, { readonly: true, fileMustExist: true })
let baseline
try {
if (additive) {
  const jiti = createJiti(import.meta.url, { fsCache: false })
  baseline = await jiti.import('../db/runtime-schema.generated.ts')
  for (const statement of baseline.runtimeSchemaStatements) db.exec(statement)
  const { upgradeTitleCycleDisposition } = await jiti.import('../db/title-cycle-disposition.ts')
  upgradeTitleCycleDisposition(db)
}
  if (!additive) assertFinalPlatformRuntime(db)
  if (db.prepare("SELECT 1 FROM sqlite_schema WHERE name='platform_runtime_capability'").get()) throw new Error('Regeneration requires a migrated authority, not a native database')
  const statements = db.prepare("SELECT sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END,name").all().map(row => row.sql)
  const capabilities = baseline?.runtimeCapabilities ?? db.prepare("SELECT DISTINCT transform_version FROM platform_migration_run WHERE state='complete' ORDER BY transform_version").all().map(row => row.transform_version)
  const hash = createHash('sha256').update(JSON.stringify(statements)).digest('hex')
  writeFileSync(new URL('../db/runtime-schema.generated.ts', import.meta.url), '// Generated by upgrade/generate-runtime-schema.mjs; schema only, no business data.\n' +
    'export const runtimeSchemaHash = ' + JSON.stringify(hash) + '\n' +
    'export const runtimeCapabilities = ' + JSON.stringify(capabilities) + '\n' +
    'export const runtimeSchemaStatements: readonly string[] = ' + JSON.stringify(statements, null, 2) + '\n')
} finally { db.close() }
