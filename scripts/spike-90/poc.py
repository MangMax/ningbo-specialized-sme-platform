"""Isolated synthetic REST/MCP transaction probe; never opens an app database."""
import argparse
import hashlib
import json
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

import psycopg
from psycopg_pool import ConnectionPool


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()


class Store:
    def __init__(self, kind, target):
        self.kind, self.target = kind, target
        self.pool = ConnectionPool(target, min_size=1, max_size=5, open=True) if kind == "postgres" else None

    @contextmanager
    def connect(self):
        if self.pool:
            with self.pool.connection() as db:
                yield db
            return
        db = sqlite3.connect(self.target, timeout=5)
        db.execute("PRAGMA foreign_keys=ON")
        db.execute("PRAGMA busy_timeout=5000")
        db.execute("PRAGMA journal_mode=WAL")
        try:
            yield db
            db.commit()
        except BaseException:
            db.rollback()
            raise
        finally:
            db.close()

    def sql(self, statement):
        return statement.replace("?", "%s") if self.kind == "postgres" else statement

    def run(self, db, statement, values=()):
        return db.execute(self.sql(statement), values)

    def init(self):
        identity = "INTEGER PRIMARY KEY AUTOINCREMENT" if self.kind == "sqlite" else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        with self.connect() as db:
            for ddl in (
                f"CREATE TABLE IF NOT EXISTS batch (id {identity}, idem TEXT NOT NULL UNIQUE, fingerprint TEXT NOT NULL, status TEXT NOT NULL, source_sha256 TEXT NOT NULL)",
                f"CREATE TABLE IF NOT EXISTS source (id {identity}, batch_id BIGINT NOT NULL REFERENCES batch(id), raw_body TEXT NOT NULL, raw_sha256 TEXT NOT NULL)",
                f"CREATE TABLE IF NOT EXISTS relation (id {identity}, source_id BIGINT NOT NULL REFERENCES source(id), sequence_no INTEGER NOT NULL, name TEXT NOT NULL, UNIQUE(source_id, sequence_no))",
                f"CREATE TABLE IF NOT EXISTS audit (id {identity}, batch_id BIGINT NOT NULL REFERENCES batch(id), event TEXT NOT NULL, previous_hash TEXT NOT NULL, entry_hash TEXT NOT NULL)",
                "CREATE INDEX IF NOT EXISTS audit_batch_idx ON audit(batch_id, id)",
            ):
                self.run(db, ddl)

    def batch(self, db, key):
        return self.run(db, "SELECT id, fingerprint, status, source_sha256 FROM batch WHERE idem=?", (key,)).fetchone()

    def receipt(self, key):
        with self.connect() as db:
            batch = self.batch(db, key)
            if not batch:
                return None
            bid, fingerprint, status, source_hash = batch
            rows = self.run(db, "SELECT event, previous_hash, entry_hash FROM audit WHERE batch_id=? ORDER BY id", (bid,)).fetchall()
            previous, valid = "0" * 64, True
            for event, prior, entry in rows:
                expected = digest(previous + "|" + event + "|" + fingerprint)
                valid = valid and prior == previous and entry == expected
                previous = entry
            return {"idempotencyKey": key, "fingerprint": fingerprint, "status": status,
                    "sourceSha256": source_hash, "auditEvents": [r[0] for r in rows],
                    "auditChainValid": valid, "auditHead": previous}

    def write(self, request, commit):
        if not isinstance(request, dict) or not isinstance(request.get("idempotencyKey"), str) or not request["idempotencyKey"]:
            return 400, {"error": "invalid_request"}
        if not isinstance(request.get("rawBody"), str) or not isinstance(request.get("relations"), list):
            return 400, {"error": "invalid_request"}
        if any(not isinstance(r, str) for r in request["relations"]):
            return 400, {"error": "invalid_request"}
        key = request["idempotencyKey"]
        body_hash = digest(request["rawBody"])
        fingerprint = digest(canonical({"rawSha256": body_hash, "relations": request["relations"]}))
        try:
            with self.connect() as db:
                if self.kind == "sqlite":
                    self.run(db, "BEGIN IMMEDIATE")
                self.run(db, "INSERT INTO batch(idem, fingerprint, status, source_sha256) VALUES(?,?,?,?) ON CONFLICT(idem) DO NOTHING",
                         (key, fingerprint, "preflight", body_hash))
                batch = self.batch(db, key)
                bid, old_fingerprint, status, _ = batch
                if old_fingerprint != fingerprint:
                    return 409, {"error": "idempotency_conflict"}
                prior = self.run(db, "SELECT entry_hash FROM audit WHERE batch_id=? ORDER BY id DESC LIMIT 1", (bid,)).fetchone()
                if not prior:
                    self.audit(db, bid, "preflight", "0" * 64, fingerprint)
                if commit and status != "committed":
                    source_id = self.run(db, "INSERT INTO source(batch_id, raw_body, raw_sha256) VALUES(?,?,?) RETURNING id",
                                         (bid, request["rawBody"], body_hash)).fetchone()[0]
                    for seq, name in enumerate(request["relations"], 1):
                        self.run(db, "INSERT INTO relation(source_id, sequence_no, name) VALUES(?,?,?)", (source_id, seq, name))
                    self.run(db, "UPDATE batch SET status='committed' WHERE id=?", (bid,))
                    prior = self.run(db, "SELECT entry_hash FROM audit WHERE batch_id=? ORDER BY id DESC LIMIT 1", (bid,)).fetchone()[0]
                    self.audit(db, bid, "commit", prior, fingerprint)
        except (sqlite3.Error, psycopg.Error) as exc:
            return 503, {"error": "storage_error", "category": type(exc).__name__}
        return 200, self.receipt(key)

    def audit(self, db, bid, event, previous, fingerprint):
        self.run(db, "INSERT INTO audit(batch_id,event,previous_hash,entry_hash) VALUES(?,?,?,?)",
                 (bid, event, previous, digest(previous + "|" + event + "|" + fingerprint)))

    def record(self, key):
        with self.connect() as db:
            batch = self.batch(db, key)
            if not batch:
                return None
            row = self.run(db, "SELECT id, raw_body, raw_sha256 FROM source WHERE batch_id=?", (batch[0],)).fetchone()
            if not row:
                return {"status": "preflight", "relations": []}
            relations = self.run(db, "SELECT sequence_no, name FROM relation WHERE source_id=? ORDER BY sequence_no", (row[0],)).fetchall()
            return {"status": "committed", "rawSha256": row[2], "rawHashValid": digest(row[1]) == row[2],
                    "relations": [{"sequenceNo": n, "name": name} for n, name in relations]}


def handler(store):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_):
            pass

        def respond(self, code, value):
            body = canonical(value).encode()
            self.send_response(code)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self):
            path = urlparse(self.path)
            key = parse_qs(path.query).get("idempotencyKey", [""])[0]
            if path.path == "/health":
                return self.respond(200, {"ok": True})
            if path.path == "/api/receipt":
                result = store.receipt(key)
            elif path.path == "/api/record":
                result = store.record(key)
            else:
                return self.respond(404, {"error": "not_found"})
            self.respond(200 if result else 404, result or {"error": "not_found"})

        def do_POST(self):
            try:
                body = json.loads(self.rfile.read(int(self.headers.get("Content-Length", "0"))))
            except (ValueError, TypeError):
                return self.respond(400, {"error": "invalid_json"})
            if self.path == "/api/preflight" or self.path == "/api/commit":
                code, result = store.write(body, self.path.endswith("commit"))
                return self.respond(code, result)
            if self.path != "/mcp" or body.get("method") != "tools/call":
                return self.respond(404, {"error": "not_found"})
            params = body.get("params") or {}
            name, args = params.get("name"), params.get("arguments") or {}
            if name == "get_receipt":
                result, code = store.receipt(args.get("idempotencyKey", "")), 200
            elif name == "get_record":
                result, code = store.record(args.get("idempotencyKey", "")), 200
            elif name == "commit_batch":
                code, result = store.write(args, True)
            else:
                result, code = {"error": "unknown_tool"}, 404
            self.respond(200, {"jsonrpc": "2.0", "id": body.get("id"), "result": {
                "content": [{"type": "text", "text": canonical(result)}], "isError": code >= 400}})
    return Handler


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("backend", choices=["sqlite", "postgres"])
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--sqlite-path")
    parser.add_argument("--skip-init", action="store_true", help="serve with an app role after owner-run migrations")
    args = parser.parse_args()
    target = args.sqlite_path if args.backend == "sqlite" else Path(os.environ.get("SPIKE90_PG_DSN_FILE", "/nonexistent")).read_text().strip()
    if not target or args.backend == "sqlite" and not os.path.abspath(target).startswith("/tmp/ningbo-perf-83-90/postgres-poc/"):
        parser.error("isolated target required")
    store = Store(args.backend, target)
    if not args.skip_init:
        store.init()
    ThreadingHTTPServer(("127.0.0.1", args.port), handler(store)).serve_forever()


if __name__ == "__main__":
    main()
