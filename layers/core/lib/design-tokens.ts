/**
 * Design Token 目录（单一事实来源）。
 *
 * 这里登记的是 `layers/core/app/assets/css/tailwind.css` 里真实存在的 CSS 变量：
 * 每一项都写明变量名、Tailwind 类、语义角色、适用场景与明暗取值。
 * `/design-tokens`（仅开发态）按本目录渲染可视化预览；
 * `tests/ui/theming/design-tokens.test.ts` 校验这里登记的名字在样式表里确实定义了。
 *
 * 加/改 token 的顺序：先改 tailwind.css，再改这里，最后更新 DESIGN.md。
 * 三处对不上时以样式表为准 —— 目录只是镜像，不是第二套定义。
 */

/** token 的定义位置：成对色板 / `@theme` 刻度 / `:root` 单值。 */
export type DesignTokenScope = 'palette' | 'theme' | 'root'

/** 预览页用哪种形态展示这一类 token。 */
export type DesignTokenPreview =
  | 'swatch'
  | 'text'
  | 'shadow'
  | 'radius'
  | 'type'
  | 'motion'
  | 'layout'

type DesignTokenBase = {
  /** CSS 变量名，如 `--page`。 */
  readonly name: `--${string}`
  /** 引用写法，如 `var(--page)`。预览页点一下复制它。 */
  readonly cssVar: `var(--${string})`
  /** 对应的 Tailwind 工具类（若有），如 `bg-page`。 */
  readonly tailwindClass?: string
  /** 中文语义说明：这个 token 回答什么问题。 */
  readonly role: string
  /** 适用场景与禁区。 */
  readonly usage: string
}

export type DesignToken =
  | (DesignTokenBase & {
      readonly scope: 'palette'
      readonly lightValue: string
      readonly darkValue: string
    })
  | (DesignTokenBase & {
      readonly scope: 'theme' | 'root'
      readonly value: string
    })

export type DesignTokenCategory = {
  readonly id: string
  readonly title: string
  readonly summary: string
  readonly preview: DesignTokenPreview
  readonly tokens: readonly DesignToken[]
}

