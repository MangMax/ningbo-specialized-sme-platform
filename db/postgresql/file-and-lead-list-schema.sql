CREATE TABLE stored_file_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stored_file_id bigint NOT NULL REFERENCES stored_file(id),
  old_display_name text NOT NULL,
  new_display_name text NOT NULL,
  created_at text NOT NULL
);
CREATE INDEX stored_file_audit_file_idx ON stored_file_audit(stored_file_id);

CREATE TABLE file_maintenance_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id bigint NOT NULL REFERENCES stored_file(id),
  revision bigint NOT NULL,
  action text NOT NULL CHECK (action IN ('update', 'remove', 'restore')),
  idempotency_key text,
  request_hash text NOT NULL,
  mode text NOT NULL CHECK (mode IN ('legacy', 'versioned')),
  actor text,
  basis text,
  before_json text NOT NULL,
  after_json text NOT NULL,
  created_at text NOT NULL,
  CONSTRAINT file_maintenance_key_uq UNIQUE (idempotency_key),
  CONSTRAINT file_maintenance_revision_uq UNIQUE (file_id, revision)
);

CREATE TABLE file_physical_intent (
  id text PRIMARY KEY,
  file_id bigint NOT NULL REFERENCES stored_file(id),
  rel_path text NOT NULL,
  sha256 text NOT NULL,
  bytes bigint NOT NULL,
  state text NOT NULL CHECK (state IN ('pending', 'quarantined', 'recovering', 'recovered')),
  delete_key text NOT NULL,
  delete_hash text NOT NULL,
  delete_receipt text,
  recover_key text,
  recover_hash text,
  recover_receipt text,
  created_at text NOT NULL,
  CONSTRAINT file_physical_delete_key_uq UNIQUE (delete_key),
  CONSTRAINT file_physical_recover_key_uq UNIQUE (recover_key)
);
CREATE UNIQUE INDEX file_physical_active_uq ON file_physical_intent(file_id) WHERE state <> 'recovered';
CREATE INDEX file_physical_history_idx ON file_physical_intent(file_id, created_at COLLATE "C", id COLLATE "C");

CREATE TABLE lead_list_version (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  series text NOT NULL,
  channel_code text NOT NULL REFERENCES enterprise_source_channel(code),
  list_type_code text NOT NULL REFERENCES enterprise_source_list_type(code),
  acquired_on text NOT NULL,
  file_id bigint NOT NULL REFERENCES stored_file(id),
  file_sha256 text NOT NULL,
  request_hash text NOT NULL,
  created_at text NOT NULL,
  UNIQUE (series, channel_code, list_type_code, acquired_on, file_id)
);
CREATE INDEX lead_list_version_file_idx ON lead_list_version(file_id);

CREATE TABLE lead_list_row (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id bigint NOT NULL REFERENCES lead_list_version(id),
  row_number bigint NOT NULL,
  name text NOT NULL,
  uscc text,
  district text,
  note text,
  enterprise_id bigint REFERENCES enterprise(id),
  review_hash text,
  review_actor text,
  review_basis text,
  reviewed_at text,
  CHECK ((enterprise_id IS NULL) = (review_hash IS NULL)),
  UNIQUE (version_id, row_number)
);

CREATE TABLE ocr_result (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id bigint NOT NULL REFERENCES stored_file(id) ON DELETE CASCADE,
  page_no bigint NOT NULL,
  revision bigint NOT NULL DEFAULT 1,
  page_rel_path text,
  markdown text NOT NULL,
  raw text,
  engine text NOT NULL DEFAULT 'paddleocr',
  model text,
  channel text NOT NULL,
  created_at text NOT NULL,
  UNIQUE (file_id,page_no)
);

CREATE TABLE lead_list_export (
  job_id text COLLATE "C" PRIMARY KEY REFERENCES job(id) ON DELETE CASCADE,
  version_id bigint NOT NULL REFERENCES lead_list_version(id),
  content text NOT NULL
);
