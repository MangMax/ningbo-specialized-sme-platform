CREATE TABLE difference_reason (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id bigint NOT NULL,
  title_code text NOT NULL,
  direction text NOT NULL,
  status text DEFAULT 'not_queried' NOT NULL,
  reason_code text,
  reason_note text,
  measure_code text,
  measure_note text,
  evidence_query_id bigint,
  evidence_relation_id bigint,
  moved_in_city text,
  moved_in_title_code text,
  moved_in_year bigint,
  moved_in_batch bigint,
  verification_status text DEFAULT 'pending' NOT NULL,
  recorded_at text NOT NULL,
  created_at text NOT NULL,
  lifecycle_action text,
  previous_id bigint,
  actor text,
  basis text,
  rule_version text,
  effective_at text,
  idempotency_key text,
  request_hash text,
  current_qualification text,
  fact_references text,
  retired_evidence_validity text CHECK (retired_evidence_validity IN ('valid', 'evidence_changed', 'premise_invalid')),
  retired_evidence_reviewed boolean
);
