-- Tagged evidence retains SQLite storage class: UTF-8 for text, original bytes for blobs,
-- eight-byte big-endian signed integers or IEEE-754 doubles for numeric cells.

CREATE TABLE platform_archive_value (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_class text NOT NULL,
  bytes bytea,
  byte_length bigint,
  sha256 text,
  created_at text,
  CONSTRAINT platform_archive_value_ck CHECK ((storage_class = 'null' AND bytes IS NULL AND byte_length IS
    NULL AND sha256 IS NULL) OR (storage_class IN ('text','blob') AND bytes IS NOT NULL AND byte_length IS
    NOT NULL AND byte_length = length(bytes) AND sha256 IS NOT NULL AND length(sha256) = 64 AND sha256 !~
    '[^0-9a-f]')),
  CHECK (sha256 IS NULL OR sha256 = encode(pg_catalog.sha256(bytes), 'hex'))
);

