CREATE TABLE official_evidence_row_revision (
  evidence_id bigint NOT NULL,
  revision bigint NOT NULL,
  format_version bigint DEFAULT 1 NOT NULL,
  event_id bigint NOT NULL,
  captured_record_id bigint NOT NULL,
  captured_enterprise_id bigint NOT NULL,
  name_raw text,
  uscc_raw text,
  district_raw text,
  source_document_id bigint,
  stored_file_id bigint,
  path text,
  sha256 text,
  bytes bigint,
  attachment text,
  section_key text,
  list_no bigint,
  page bigint,
  source_binding_known bigint NOT NULL,
  actor text NOT NULL,
  basis text NOT NULL,
  command_kind text NOT NULL,
  import_batch_id bigint,
  correction_batch_key text,
  created_at text NOT NULL,
  CONSTRAINT official_evidence_row_version_ck CHECK (format_version = 1 AND revision BETWEEN 1 AND 9007199254740991),
  CONSTRAINT official_evidence_row_ids_ck CHECK (
    evidence_id BETWEEN 1 AND 9007199254740991 AND event_id BETWEEN 1 AND 9007199254740991
    AND captured_record_id BETWEEN 1 AND 9007199254740991 AND captured_enterprise_id BETWEEN 1 AND 9007199254740991
  ),
  CONSTRAINT official_evidence_row_optional_ids_ck CHECK (
    (source_document_id IS NULL OR source_document_id BETWEEN 1 AND 9007199254740991)
    AND (stored_file_id IS NULL OR stored_file_id BETWEEN 1 AND 9007199254740991)
    AND (list_no IS NULL OR list_no BETWEEN 1 AND 9007199254740991)
    AND (page IS NULL OR page BETWEEN 1 AND 9007199254740991)
    AND (import_batch_id IS NULL OR import_batch_id BETWEEN 1 AND 9007199254740991)
  ),
  CONSTRAINT official_evidence_row_bytes_ck CHECK (bytes BETWEEN 0 AND 9007199254740991),
  CONSTRAINT official_evidence_row_binding_ck CHECK (source_binding_known IN (0,1) AND (source_binding_known = 0 OR (
    source_document_id IS NOT NULL AND sha256 IS NOT NULL AND length(sha256) = 64 AND sha256 !~ '[^0-9a-f]' AND
    bytes IS NOT NULL AND section_key IS NOT NULL AND octet_length(section_key) > 0 AND list_no IS NOT NULL))),
  CONSTRAINT official_evidence_row_actor_ck CHECK (
    CASE WHEN actor IS JSON OBJECT THEN coalesce(
      actor::json->>'type' IN ('user', 'agent') AND json_typeof(actor::json->'id') = 'string'
      AND length(actor::json->>'id') > 0, false
    ) ELSE false END),
  CONSTRAINT official_evidence_row_command_ck CHECK (
    (command_kind = 'import' AND import_batch_id IS NOT NULL AND correction_batch_key IS NULL) OR
    (command_kind = 'evidence_correction' AND correction_batch_key IS NOT NULL AND import_batch_id IS NULL))
);

