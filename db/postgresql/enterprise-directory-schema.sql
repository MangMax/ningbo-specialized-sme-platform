CREATE TABLE service_credential (
  key text PRIMARY KEY,
  value text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE enterprise (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uscc_norm text UNIQUE,
  name text NOT NULL,
  name_norm text NOT NULL,
  district text,
  city text,
  reg_status text,
  quality_flags text DEFAULT '[]'
);

CREATE TABLE enterprise_merge (
  from_enterprise_id bigint PRIMARY KEY REFERENCES enterprise(id) ON DELETE RESTRICT,
  into_enterprise_id bigint NOT NULL REFERENCES enterprise(id) ON DELETE RESTRICT,
  basis text NOT NULL,
  recorded_at text NOT NULL,
  CHECK (from_enterprise_id <> into_enterprise_id),
  CHECK (from_enterprise_id BETWEEN 1 AND 9007199254740991),
  CHECK (into_enterprise_id BETWEEN 1 AND 9007199254740991)
);

CREATE TABLE enterprise_region (
  code text PRIMARY KEY,
  name text NOT NULL,
  parent_code text REFERENCES enterprise_region(code),
  level bigint NOT NULL CHECK (level BETWEEN 1 AND 3)
);

CREATE TABLE enterprise_industry (
  code text PRIMARY KEY,
  input_id text NOT NULL UNIQUE,
  name text NOT NULL,
  parent_code text REFERENCES enterprise_industry(code),
  level bigint NOT NULL CHECK (level BETWEEN 0 AND 3),
  description text
);

CREATE TABLE enterprise_directory (
  enterprise_id bigint PRIMARY KEY REFERENCES enterprise(id),
  district_code text REFERENCES enterprise_region(code),
  township_code text REFERENCES enterprise_region(code),
  industry_code text REFERENCES enterprise_industry(code),
  removed_reason text,
  revision bigint NOT NULL DEFAULT 1
);

CREATE TABLE enterprise_address (
  enterprise_id bigint NOT NULL REFERENCES enterprise(id),
  kind text NOT NULL CHECK (kind IN ('registered', 'operating')),
  address text NOT NULL CHECK (length(trim(address)) BETWEEN 1 AND 500),
  PRIMARY KEY (enterprise_id, kind)
);

CREATE TABLE stored_file (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rel_path text NOT NULL UNIQUE,
  display_name text,
  filename text NOT NULL,
  ext text NOT NULL,
  bytes bigint NOT NULL,
  sha256 text NOT NULL,
  created_at text NOT NULL,
  removed_at text
);

CREATE TABLE enterprise_source_channel (code text PRIMARY KEY, name text NOT NULL);
CREATE TABLE enterprise_source_list_type (code text PRIMARY KEY, name text NOT NULL);

CREATE TABLE enterprise_source (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module text NOT NULL,
  business_table text NOT NULL,
  version_key text NOT NULL,
  channel_code text NOT NULL REFERENCES enterprise_source_channel(code),
  list_type_code text NOT NULL REFERENCES enterprise_source_list_type(code),
  acquired_on text,
  series text NOT NULL,
  file_id bigint REFERENCES stored_file(id),
  sha256 text,
  UNIQUE (module, business_table, version_key)
);

CREATE TABLE enterprise_source_link (
  enterprise_id bigint NOT NULL REFERENCES enterprise(id),
  source_id bigint NOT NULL REFERENCES enterprise_source(id),
  PRIMARY KEY (enterprise_id, source_id)
);
