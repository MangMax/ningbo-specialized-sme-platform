CREATE TABLE log_policy (
  id bigint PRIMARY KEY CHECK (id = 1),
  "retentionDays" bigint NOT NULL CHECK ("retentionDays" BETWEEN 1 AND 365),
  "maxBytes" bigint NOT NULL CHECK ("maxBytes" BETWEEN 1048576 AND 4294967296),
  pruned bigint NOT NULL DEFAULT 0 CHECK (pruned >= 0),
  cleared bigint NOT NULL DEFAULT 0 CHECK (cleared >= 0),
  logical_bytes bigint NOT NULL DEFAULT 0 CHECK (logical_bytes >= 0)
);

CREATE TABLE log_collection (
  id bigint PRIMARY KEY CHECK (id = 1),
  collection text NOT NULL,
  revision bigint NOT NULL CHECK (revision BETWEEN 0 AND 9007199254740991)
);

CREATE TABLE log_events (
  seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id text COLLATE "C" NOT NULL UNIQUE,
  timestamp text COLLATE "C" NOT NULL,
  level text COLLATE "C" NOT NULL,
  source text COLLATE "C" NOT NULL,
  module text COLLATE "C",
  operation text COLLATE "C" NOT NULL,
  outcome text COLLATE "C" NOT NULL,
  "requestId" text COLLATE "C",
  "traceId" text COLLATE "C",
  "taskId" text COLLATE "C",
  "fileId" bigint,
  "batchId" text COLLATE "C",
  "resourceId" text COLLATE "C",
  detail text NOT NULL
);
